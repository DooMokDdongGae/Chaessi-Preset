// package.json is the single editable version source; browser modules use this generated constant.
import {readFile,writeFile} from 'node:fs/promises';
const version=JSON.parse(await readFile(new URL('../package.json',import.meta.url),'utf8')).version;
await writeFile(new URL('../src/state/build-version.js',import.meta.url),`// Generated by scripts/sync-version.mjs from package.json.\nexport const APP_VERSION = ${JSON.stringify(version)};\n`);
